def value_band(v: float) -> int:
    return 1 if v < 1 else 2 if v < 5 else 3 if v < 15 else 4 if v < 40 else 5


def score(u) -> dict:
    uid, name, site, what, level, conseq, value, years, events, tags, base, share, mwh, auth = u
    crit = [years >= 2, events is None or events >= 30, tags, base, share]
    net = round(value - mwh * PRICE_PER_MWH / 1e6, 2)
    return {"id": uid, "name": name, "level": level, "consequence": conseq,
            "value": value, "energy_cost_m": round(mwh * PRICE_PER_MWH / 1e6, 2), "net_value": net,
            "value_score": value_band(net), "value_score_before_energy": value_band(value),
            "readiness": max(1, sum(crit)), "criteria": [int(c) for c in crit],
            "tier": TIER[(conseq, level)], "needs_authority": level != "advisory", "authority": auth}


